def generate_icons():
    header = '''<svg
  xmlns="http://www.w3.org/2000/svg"
  width="24"
  height="24"
  viewBox="0 0 24 24"
  fill="none"
  stroke="#0284C7"
  stroke-width="2"
  stroke-linecap="round"
  stroke-linejoin="round"
>
'''
    footer = '\n</svg>\n'

    created = 0
    for name, inner in ICON_SVGS.items():
        svg_code = header + "  " + inner + footer
        # Validate XML
        try:
            ET.fromstring(svg_code)
        except Exception as e:
            print(f"Error in {name}: {e}")
            continue

        icon_path = ICONS_DIR / f"{name}.svg"
        with open(icon_path, "w", encoding="utf-8") as f:
            f.write(svg_code)
        created += 1

    print(f"Successfully validated and wrote {created} SVG icons to {ICONS_DIR}")

if __name__ == "__main__":
    generate_icons()
